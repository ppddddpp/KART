        assert disc_ex <= 0.01, f"{label} discrepancy {disc_ex*100:.4f}% > 1%"
        print(f"  [PASS] Extra FMNIST Config ({label}): (D={D_ex}, R={R_ex}, H={H_ex}) -> "
              f"{tot_ex} params (diff: {tot_ex - target_total_params:+d}, {disc_ex*100:.4f}%)")

