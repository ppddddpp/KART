class DenseResMLPLayer(nn.Module):
    def __init__(self, d_model: int):
        super().__init__()
        self.fc1 = nn.Linear(d_model, d_model)
        self.act = nn.SiLU()
        self.fc2 = nn.Linear(d_model, d_model)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.fc2(self.act(self.fc1(x)))


class DenseResMLPRegressor(nn.Module):
    """
    Residual Dense MLP for Regression with Identity Stem matching KARTRegressor.
    """
    def __init__(self, input_dim: int, num_layers: int):
        super().__init__()
        self.num_layers = num_layers
        self.stem = nn.Identity()
        self.layers = nn.ModuleList([DenseResMLPLayer(input_dim) for _ in range(num_layers)])
        self.beta_L = 1.0 / math.sqrt(num_layers) if num_layers > 0 else 1.0
        self.head = nn.Linear(input_dim, 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.stem(x)
        for layer in self.layers:
            x = x + self.beta_L * layer(x)
        return self.head(x)

    def count_parameters(self) -> int:
        return sum(p.numel() for p in self.parameters() if p.requires_grad)

    def count_branch_parameters(self) -> int:
        return sum(p.numel() for layer in self.layers for p in layer.parameters() if p.requires_grad)


def count_model_parameters(model: nn.Module) -> int:
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def count_model_branch_parameters(model: nn.Module) -> int:
    layers = getattr(model, "layers", None)
    if isinstance(layers, (nn.ModuleList, list, tuple)):
        return sum(p.numel() for layer in layers for p in layer.parameters() if p.requires_grad)
    return count_model_parameters(model)


def get_matrix_multiply_flops_lr_mlp(
    d_model: int,
    num_layers: int,
    batch_size: int,
    D: int,
    R: int,
    H: int,
    input_dim: int = 784,
    output_dim: int = 10
) -> int:
    """
    Matrix-multiply FLOP estimate under the same convention used by Cases 1-3.
    """
    B = batch_size
    stem_macs = B * input_dim * d_model
    layer_macs = (B * d_model * D) + (B * D * H) + (B * H * R) + (B * R * d_model)
    head_macs = B * d_model * output_dim
    return int((stem_macs + (layer_macs * num_layers) + head_macs) * 2)

def generate_interaction_data(num_samples: int = 10000, seed: int = 42) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Task A: Non-additive interaction DGP from Case 5.
    X ~ U(0, 1)^10
    y = sin(pi * X0 * X1) + (X2 - X3)^2
    """
    set_seed(seed)
    g = torch.Generator().manual_seed(seed)
    X = torch.rand(num_samples, 10, generator=g)
    y = torch.sin(math.pi * X[:, 0] * X[:, 1]) + (X[:, 2] - X[:, 3]) ** 2
    return X, y.unsqueeze(1)


def generate_low_rank_teacher_data(
    num_samples: int = 10000,
    seed: int = 42
) -> Tuple[torch.Tensor, torch.Tensor, LowRankMLPRegressor]:
    """
    Task B: Target strictly generated by a frozen residual Low-Rank MLP Regressor.
    teacher: LowRankMLPRegressor(input_dim=10, num_layers=2, D=2, R=2, H=4, use_domain_bound=False)
    X ~ U(0, 1)^10, y = teacher(X)
    """
    set_seed(seed)
    g = torch.Generator().manual_seed(seed)
    X = torch.rand(num_samples, 10, generator=g)

    teacher = LowRankMLPRegressor(
        input_dim=10,
        num_layers=2,
        D=2,
        R=2,
        H=4,
        act_type='silu',
        use_domain_bound=False
    )
    for p in teacher.parameters():
        p.requires_grad = False
    teacher.eval()

    with torch.no_grad():
        y = teacher(X)

    return X, y, teacher

def run_preflight_validation(device: torch.device):
    print("\n" + "=" * 80)
    print("[CHECK] RUNNING PREFLIGHT VALIDATION BEFORE TRAINING")
    print("=" * 80)

    # 1. Parameter solver verification for Fashion-MNIST
    n, d_out, L = 64, 64, 3
    kart_cfg = KARTConfig(in_features=64, out_features=64, Q=4, D=8, R=8, K=8, M=8, basis_type='fourier')
    dummy_kart_layer = KARTNet(784, 10, 64, 3, kart_cfg).layers[0]
    target_branch_params = sum(p.numel() for p in dummy_kart_layer.parameters() if p.requires_grad)
    stem_head_params = (784 * 64 + 64) + (64 * 2) + (64 * 10 + 10)
    target_total_params = stem_head_params + L * target_branch_params

    assert target_branch_params == 5152, f"Expected KART branch params 5152, got {target_branch_params}"
    assert target_total_params == 66474, f"Expected KART total params 66474, got {target_total_params}"

    D_f, R_f, H_f, info_f = solve_param_matched_lr_config(
        n=n,
        d_out=d_out,
        target_branch_params=target_branch_params,
        D_target=8,
        R_target=8,
        H_target=32,
        num_layers=L,
        stem_head_params=stem_head_params,
        enforce_symmetric=True
    )
    assert (D_f, R_f, H_f) == (23, 23, 47), f"Expected (23, 23, 47), got {(D_f, R_f, H_f)}"
    assert info_f["total_discrepancy"] <= 0.01, f"Total discrepancy > 1%: {info_f['total_discrepancy']}"
    assert abs(info_f["total_discrepancy"] - 3 / 66474) < 1e-6, "Whole-network discrepancy mismatch"
    assert abs(info_f["branch_discrepancy"] - 1 / 5152) < 1e-6, "Branch discrepancy mismatch"

    net_lr_param = LowRankMLPNet(784, 10, 64, 3, D_f, R_f, H_f, use_domain_bound=True)
    actual_total = net_lr_param.count_parameters()
    actual_branch = net_lr_param.count_branch_parameters()
    assert actual_total == 66477, f"Expected 66477 total params, got {actual_total}"
    assert actual_branch == 15459, f"Expected 15459 branch params, got {actual_branch}"
    print(f"  [PASS] Fashion-MNIST Parameter Matching: (D={D_f}, R={R_f}, H={H_f}) -> "
          f"Branch discrepancy = {info_f['branch_discrepancy']*100:.4f}%, "
          f"Whole-network discrepancy = {info_f['total_discrepancy']*100:.4f}%")

    # 2. Parameter solver verification for Synthetic
    syn_n, syn_L = 10, 2
    syn_kart_cfg = KARTConfig(in_features=10, out_features=10, Q=4, D=8, R=8, K=8, M=8, basis_type='fourier')
    dummy_syn_kart_layer = KARTRegressor(10, 2, syn_kart_cfg).layers[0]
